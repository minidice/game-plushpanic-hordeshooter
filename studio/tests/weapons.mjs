import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('../../', import.meta.url));
const origin = process.env.STUDIO_URL || 'http://127.0.0.1:4317';
let checks = 0;
const check = (value, message) => { assert.ok(value, message); checks++; console.log('PASS ' + message); };
const page = await fetch(origin + '/weapons');
check(page.status === 200 && (await page.text()).includes('무기 도감'), 'weapon library page served');
for (const file of ['/weapons.js', '/weapons.css']) check((await fetch(origin + file)).status === 200, `${file} served`);
const response = await fetch(origin + '/api/weapons');
check(response.status === 200, 'weapons endpoint available');
const data = await response.json();
check(data.warnings.length === 0, 'weapon data loads without warnings');
const ids = (await readFile(path.join(root, 'game/content/data/weapons.csv'), 'utf8')).split(/\r?\n/).slice(1).filter(l => l && !l.startsWith('#')).map(l => l.split(',')[0]);
for (const id of ids) check(data.weapons.some(w => w.id === id), `${id}: listed`);
check(data.weapons.some(w => w.dual), 'dual-wield variants listed');
check(new Set(data.weapons.map(w => w.id)).size === data.weapons.length, 'unique IDs');
const m4 = data.weapons.find(w => w.id === 'm4'), ak = data.weapons.find(w => w.id === 'ak47');
check(m4.cone.aim < m4.cone.hip && m4.rows.some(r => r.label.includes('aim_time_s')), 'M4 shows hip and aimed cones and aim time');
check(m4.recoil.trace.length === Math.min(50, data.traceShots) && m4.recoil.trace[0][1] === -m4.recoil.up, 'recoil trace is one magazine and starts one kick up');
const awm = data.weapons.find(w => w.id === 'awm');
check(awm.rows.some(r => r.value.startsWith(`${awm.recoil.trace.length}발`)) && awm.recoil.trace.length < m4.recoil.trace.length, 'a sniper traces its own (smaller) magazine');
check(Math.abs(ak.recoil.trace.at(-1)[1]) > Math.abs(m4.recoil.trace.at(-1)[1]) || ak.recoil.up > m4.recoil.up, 'AK climbs further than M4');
const pan = data.weapons.find(w => w.melee);
check(pan && pan.recoil.trace.length === 0, 'melee has no recoil trace');
for (const w of data.weapons) check(w.rows.length > 10 && w.source, `${w.id}: properties and source`);
console.log(`STUDIO_WEAPONS_PASS ${checks}`);
